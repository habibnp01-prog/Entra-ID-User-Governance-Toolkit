#requires -Version 5.1

<#
.SYNOPSIS
    Identifies Microsoft Entra ID guest users that may require governance review.

.DESCRIPTION
    Reads the latest Entra user discovery report generated by
    01-Get-EntraUsers.ps1 and evaluates users whose UserType is Guest.

    Detection categories:

    - ActiveGuest
    - InactiveGuest
    - NeverSignedInGuest
    - DisabledGuest

    Additional governance indicators:

    - Licensed guest
    - Inactive guest
    - Never signed-in guest
    - Disabled guest

    The script is READ-ONLY.

    No guest account is modified, disabled, deleted, or unlicensed.

.PARAMETER InactiveDays
    Number of days without a successful sign-in before an enabled
    guest is considered inactive.

    Default:
        90 days

.EXAMPLE
    .\04-Find-GuestUsers.ps1

    Uses the default 90-day inactivity threshold.

.EXAMPLE
    .\04-Find-GuestUsers.ps1 -InactiveDays 30

    Uses a 30-day inactivity threshold.

.NOTES
    Project:
        Entra ID User Governance Toolkit

    Script:
        04-Find-GuestUsers.ps1

    Version:
        1.0.0

    Data source:
        Reports\EntraUsers_*.csv

    Action:
        Read-only
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory = $false)]
    [ValidateRange(1, 3650)]
    [int]$InactiveDays = 90
)

$ErrorActionPreference = "Stop"

# ============================================================
# PROJECT PATH
# ============================================================

$ProjectRoot = Split-Path -Parent $PSScriptRoot

$ReportsPath = Join-Path $ProjectRoot "Reports"

if (-not (Test-Path $ReportsPath)) {

    New-Item `
        -Path $ReportsPath `
        -ItemType Directory `
        -Force |
        Out-Null
}

# ============================================================
# HEADER
# ============================================================

Write-Host ""
Write-Host "=============================================" -ForegroundColor Cyan
Write-Host " Entra ID User Governance Toolkit" -ForegroundColor Cyan
Write-Host " 04 - Find Guest Users" -ForegroundColor Cyan
Write-Host "=============================================" -ForegroundColor Cyan
Write-Host ""

Write-Host "Guest inactivity threshold: $InactiveDays days" -ForegroundColor Yellow
Write-Host ""

# ============================================================
# FIND LATEST USER DISCOVERY REPORT
# ============================================================

Write-Host "[1/6] Searching for Entra user discovery report..." -ForegroundColor Yellow

$InputReports = @(
    Get-ChildItem `
        -Path $ReportsPath `
        -Filter "EntraUsers_*.csv" `
        -File `
        -ErrorAction SilentlyContinue |
    Sort-Object LastWriteTime -Descending
)

if ($InputReports.Count -eq 0) {

    throw @"
No Entra user discovery report was found.

Please run:

.\Scripts\01-Get-EntraUsers.ps1

before running this script.
"@
}

$InputReport = $InputReports[0]

Write-Host "Using report:" -ForegroundColor Green
Write-Host "  $($InputReport.FullName)" -ForegroundColor Green
Write-Host ""

# ============================================================
# IMPORT USER REPORT
# ============================================================

Write-Host "[2/6] Loading Entra user data..." -ForegroundColor Yellow

$Users = @(
    Import-Csv -Path $InputReport.FullName
)

if ($Users.Count -eq 0) {

    throw "The selected Entra user report contains no records."
}

Write-Host "Users loaded: $($Users.Count)" -ForegroundColor Green
Write-Host ""

# ============================================================
# FILTER GUEST USERS
# ============================================================

Write-Host "[3/6] Identifying guest users..." -ForegroundColor Yellow

$GuestUsers = @(
    $Users |
    Where-Object {
        $_.UserType -eq "Guest"
    }
)

Write-Host "Guest users found: $($GuestUsers.Count)" -ForegroundColor Green
Write-Host ""

if ($GuestUsers.Count -eq 0) {

    Write-Host "No guest users were found." -ForegroundColor Yellow

    $Timestamp = Get-Date -Format "yyyyMMdd_HHmmss"

    $EmptyReportPath = Join-Path `
        $ReportsPath `
        "GuestUsers_$Timestamp.csv"

    @(
        [PSCustomObject]@{
            Id                            = ""
            DisplayName                  = ""
            UserPrincipalName            = ""
            Mail                         = ""
            AccountEnabled               = ""
            UserType                     = ""
            Department                   = ""
            JobTitle                     = ""
            CompanyName                 = ""
            EmployeeId                  = ""
            CreatedDateTime             = ""
            LastSuccessfulSignInDateTime = ""
            DaysSinceLastSuccessfulSignIn = ""
            AssignedLicenseCount         = ""
            InactivityThresholdDays      = $InactiveDays
            Category                     = "NoGuestUsers"
            GovernanceCandidate          = $false
            Reason                       = "No guest users were found in the source report."
        }
    ) |
    Export-Csv `
        -Path $EmptyReportPath `
        -NoTypeInformation `
        -Encoding UTF8

    Write-Host "Report:" -ForegroundColor Green
    Write-Host $EmptyReportPath -ForegroundColor Green
    Write-Host ""
    Write-Host "Script completed successfully." -ForegroundColor Green

    exit 0
}

# ============================================================
# CALCULATE INACTIVITY THRESHOLD
# ============================================================

$Today = (Get-Date).Date

$InactiveThresholdDate = $Today.AddDays(-$InactiveDays)

Write-Host "[4/6] Evaluating guest activity..." -ForegroundColor Yellow
Write-Host ""
Write-Host "Today:" -ForegroundColor DarkGray
Write-Host "  $($Today.ToString('yyyy-MM-dd'))" -ForegroundColor DarkGray
Write-Host ""
Write-Host "Inactive threshold:" -ForegroundColor DarkGray
Write-Host "  $($InactiveThresholdDate.ToString('yyyy-MM-dd'))" -ForegroundColor DarkGray
Write-Host ""

# ============================================================
# ANALYZE GUEST USERS
# ============================================================

$Results = foreach ($User in $GuestUsers) {

    $Category = "ActiveGuest"

    $Reason = ""

    $LastSuccessfulSignIn = $null

    $DaysSinceLastSuccessfulSignIn = $null

    # --------------------------------------------------------
    # ACCOUNT STATUS
    # --------------------------------------------------------

    $AccountEnabled = $false

    if ($User.AccountEnabled -eq "True") {
        $AccountEnabled = $true
    }

    # --------------------------------------------------------
    # LICENSE COUNT
    # --------------------------------------------------------

    $LicenseCount = 0

    if (
        -not [string]::IsNullOrWhiteSpace(
            [string]$User.AssignedLicenseCount
        )
    ) {

        $ParsedLicenseCount = 0

        if (
            [int]::TryParse(
                [string]$User.AssignedLicenseCount,
                [ref]$ParsedLicenseCount
            )
        ) {

            $LicenseCount = $ParsedLicenseCount
        }
    }

    $HasLicense = $LicenseCount -gt 0

    # --------------------------------------------------------
    # SUCCESSFUL SIGN-IN
    # --------------------------------------------------------

    $RawSignInDate = $User.LastSuccessfulSignInDateTime

    if (
        -not [string]::IsNullOrWhiteSpace(
            [string]$RawSignInDate
        )
    ) {

        $ParsedSignInDate = [datetime]::MinValue

        $DateParsed = [datetime]::TryParse(
            [string]$RawSignInDate,
            [ref]$ParsedSignInDate
        )

        if ($DateParsed) {

            $LastSuccessfulSignIn = $ParsedSignInDate

            $DaysSinceLastSuccessfulSignIn = (
                $Today - $LastSuccessfulSignIn.Date
            ).Days
        }
    }

    # --------------------------------------------------------
    # CLASSIFICATION
    # --------------------------------------------------------

    if (-not $AccountEnabled) {

        $Category = "DisabledGuest"

        $Reason = "Guest account is disabled."

    }
    elseif ($null -eq $LastSuccessfulSignIn) {

        $Category = "NeverSignedInGuest"

        $Reason = "Guest has no recorded successful sign-in activity."

    }
    elseif (
        $LastSuccessfulSignIn.Date -lt
        $InactiveThresholdDate
    ) {

        $Category = "InactiveGuest"

        $Reason = "Guest has not successfully signed in within the configured inactivity threshold."

    }
    else {

        $Category = "ActiveGuest"

        $Reason = "Guest has successful sign-in activity within the configured threshold."

    }

    # --------------------------------------------------------
    # GOVERNANCE INDICATORS
    # --------------------------------------------------------

    $GovernanceCandidate = $false

    if (
        $Category -eq "InactiveGuest" -or
        $Category -eq "NeverSignedInGuest"
    ) {

        $GovernanceCandidate = $true
    }

    # --------------------------------------------------------
    # ADDITIONAL RISK INDICATOR
    # --------------------------------------------------------

    $LicensedGovernanceFlag = $false

    if (
        $HasLicense -and
        (
            $Category -eq "InactiveGuest" -or
            $Category -eq "NeverSignedInGuest"
        )
    ) {

        $LicensedGovernanceFlag = $true
    }

    # --------------------------------------------------------
    # RESULT OBJECT
    # --------------------------------------------------------

    [PSCustomObject]@{

        Id                            = $User.Id

        DisplayName                  = $User.DisplayName

        UserPrincipalName            = $User.UserPrincipalName

        Mail                          = $User.Mail

        AccountEnabled               = $AccountEnabled

        UserType                     = $User.UserType

        Department                   = $User.Department

        JobTitle                     = $User.JobTitle

        CompanyName                  = $User.CompanyName

        EmployeeId                   = $User.EmployeeId

        CreatedDateTime              = $User.CreatedDateTime

        LastSuccessfulSignInDateTime = $LastSuccessfulSignIn

        DaysSinceLastSuccessfulSignIn = $DaysSinceLastSuccessfulSignIn

        AssignedLicenseCount         = $LicenseCount

        HasLicense                   = $HasLicense

        InactivityThresholdDays      = $InactiveDays

        InactivityThresholdDate      = $InactiveThresholdDate

        Category                     = $Category

        GovernanceCandidate          = $GovernanceCandidate

        LicensedGovernanceFlag       = $LicensedGovernanceFlag

        Reason                       = $Reason
    }
}

# ============================================================
# EXPORT REPORT
# ============================================================

Write-Host ""
Write-Host "[5/6] Generating guest governance report..." -ForegroundColor Yellow

$Timestamp = Get-Date -Format "yyyyMMdd_HHmmss"

$OutputPath = Join-Path `
    $ReportsPath `
    "GuestUsers_$Timestamp.csv"

$Results |
    Export-Csv `
        -Path $OutputPath `
        -NoTypeInformation `
        -Encoding UTF8

# ============================================================
# SUMMARY
# ============================================================

Write-Host ""
Write-Host "[6/6] Analysis completed." -ForegroundColor Yellow
Write-Host ""

$TotalGuests = @($Results).Count

$ActiveGuests = @(
    $Results |
    Where-Object {
        $_.Category -eq "ActiveGuest"
    }
).Count

$InactiveGuests = @(
    $Results |
    Where-Object {
        $_.Category -eq "InactiveGuest"
    }
).Count

$NeverSignedInGuests = @(
    $Results |
    Where-Object {
        $_.Category -eq "NeverSignedInGuest"
    }
).Count

$DisabledGuests = @(
    $Results |
    Where-Object {
        $_.Category -eq "DisabledGuest"
    }
).Count

$LicensedGuests = @(
    $Results |
    Where-Object {
        $_.HasLicense -eq $true
    }
).Count

$GovernanceCandidates = @(
    $Results |
    Where-Object {
        $_.GovernanceCandidate -eq $true
    }
).Count

$LicensedGovernanceCandidates = @(
    $Results |
    Where-Object {
        $_.LicensedGovernanceFlag -eq $true
    }
).Count

# ============================================================
# DISPLAY SUMMARY
# ============================================================

Write-Host "=============================================" -ForegroundColor Cyan
Write-Host " Guest Governance Summary" -ForegroundColor Cyan
Write-Host "=============================================" -ForegroundColor Cyan

Write-Host "Total Guest Users           : $TotalGuests"
Write-Host "Active Guests               : $ActiveGuests"
Write-Host "Inactive Guests             : $InactiveGuests"
Write-Host "Never Signed-In Guests     : $NeverSignedInGuests"
Write-Host "Disabled Guests             : $DisabledGuests"
Write-Host "Licensed Guests             : $LicensedGuests"
Write-Host "Governance Candidates       : $GovernanceCandidates"
Write-Host "Inactive/Never-Signed + Licensed : $LicensedGovernanceCandidates"
Write-Host "Inactivity Threshold        : $InactiveDays days"

Write-Host ""
Write-Host "Report:" -ForegroundColor Green
Write-Host $OutputPath -ForegroundColor Green

Write-Host ""
Write-Host "Classification:" -ForegroundColor Cyan
Write-Host "  ActiveGuest          = Active guest with recent successful sign-in"
Write-Host "  InactiveGuest        = No successful sign-in within threshold"
Write-Host "  NeverSignedInGuest   = No successful sign-in recorded"
Write-Host "  DisabledGuest        = Guest account is disabled"

Write-Host ""
Write-Host "Governance candidates are READ-ONLY findings." -ForegroundColor Yellow
Write-Host "No guest accounts were modified." -ForegroundColor Green
Write-Host ""
Write-Host "Script completed successfully." -ForegroundColor Green
Write-Host ""