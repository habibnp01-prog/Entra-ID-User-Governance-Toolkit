#requires -Version 5.1

<#
.SYNOPSIS
    Identifies inactive Microsoft Entra ID users based on successful sign-in activity.

.DESCRIPTION
    Reads the latest Entra user discovery report generated by
    01-Get-EntraUsers.ps1 and identifies users who may be inactive.

    Detection categories:

    - Active
    - Inactive
    - NeverSignedIn
    - Disabled

    The script is READ-ONLY.

    No user account is modified, disabled, deleted, or licensed/unlicensed.

.PARAMETER InactiveDays
    Number of days without a successful sign-in before a user is
    considered inactive.

    Default:
        90 days

.EXAMPLE
    .\02-Find-InactiveUsers.ps1

    Uses the default 90-day inactivity threshold.

.EXAMPLE
    .\02-Find-InactiveUsers.ps1 -InactiveDays 30

    Uses a 30-day inactivity threshold.

.EXAMPLE
    .\02-Find-InactiveUsers.ps1 -InactiveDays 60

    Uses a 60-day inactivity threshold.

.NOTES
    Project:
        Entra ID User Governance Toolkit

    Script:
        02-Find-InactiveUsers.ps1

    Version:
        1.0.0

    Data source:
        Reports\EntraUsers_*.csv

    Action:
        Read-only
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory = $false)]
    [ValidateRange(1, 3650)]
    [int]$InactiveDays = 90
)

$ErrorActionPreference = "Stop"

# ============================================================
# PROJECT PATH
# ============================================================

$ProjectRoot = Split-Path -Parent $PSScriptRoot

$ReportsPath = Join-Path $ProjectRoot "Reports"

if (-not (Test-Path $ReportsPath)) {

    New-Item `
        -Path $ReportsPath `
        -ItemType Directory `
        -Force |
        Out-Null
}

# ============================================================
# HEADER
# ============================================================

Write-Host ""
Write-Host "=============================================" -ForegroundColor Cyan
Write-Host " Entra ID User Governance Toolkit" -ForegroundColor Cyan
Write-Host " 02 - Find Inactive Users" -ForegroundColor Cyan
Write-Host "=============================================" -ForegroundColor Cyan
Write-Host ""

Write-Host "Inactivity threshold: $InactiveDays days" -ForegroundColor Yellow
Write-Host ""

# ============================================================
# FIND LATEST USER DISCOVERY REPORT
# ============================================================

Write-Host "[1/5] Searching for Entra user discovery report..." -ForegroundColor Yellow

$InputReports = @(
    Get-ChildItem `
        -Path $ReportsPath `
        -Filter "EntraUsers_*.csv" `
        -File `
        -ErrorAction SilentlyContinue |
    Sort-Object LastWriteTime -Descending
)

if ($InputReports.Count -eq 0) {

    throw @"
No Entra user discovery report was found.

Please run:

.\Scripts\01-Get-EntraUsers.ps1

before running this script.
"@
}

$InputReport = $InputReports[0]

Write-Host "Using report:" -ForegroundColor Green
Write-Host "  $($InputReport.FullName)" -ForegroundColor Green
Write-Host ""

# ============================================================
# IMPORT USER REPORT
# ============================================================

Write-Host "[2/5] Loading Entra user data..." -ForegroundColor Yellow

$Users = @(
    Import-Csv -Path $InputReport.FullName
)

if ($Users.Count -eq 0) {

    throw "The selected Entra user report contains no records."
}

Write-Host "Users loaded: $($Users.Count)" -ForegroundColor Green
Write-Host ""

# ============================================================
# CALCULATE THRESHOLD
# ============================================================

$Today = (Get-Date).Date

$InactiveThresholdDate = $Today.AddDays(-$InactiveDays)

Write-Host "[3/5] Evaluating sign-in activity..." -ForegroundColor Yellow
Write-Host ""
Write-Host "Today:" -ForegroundColor DarkGray
Write-Host "  $($Today.ToString('yyyy-MM-dd'))" -ForegroundColor DarkGray
Write-Host ""
Write-Host "Inactive threshold:" -ForegroundColor DarkGray
Write-Host "  $($InactiveThresholdDate.ToString('yyyy-MM-dd'))" -ForegroundColor DarkGray
Write-Host ""

# ============================================================
# ANALYZE USERS
# ============================================================

$Results = foreach ($User in $Users) {

    $Category = "Active"
    $Reason = ""
    $LastSuccessfulSignIn = $null
    $DaysSinceLastSuccessfulSignIn = $null

    # --------------------------------------------------------
    # Account status
    # --------------------------------------------------------

    $AccountEnabled = $false

    if ($User.AccountEnabled -eq "True") {
        $AccountEnabled = $true
    }

    # --------------------------------------------------------
    # Parse successful sign-in date
    # --------------------------------------------------------

    $RawSignInDate = $User.LastSuccessfulSignInDateTime

    if (
        [string]::IsNullOrWhiteSpace(
            [string]$RawSignInDate
        )
    ) {

        $LastSuccessfulSignIn = $null

    }
    else {

        $ParsedDate = [datetime]::MinValue

        $DateParsed = [datetime]::TryParse(
            [string]$RawSignInDate,
            [ref]$ParsedDate
        )

        if ($DateParsed) {

            $LastSuccessfulSignIn = $ParsedDate
        }
    }

    # --------------------------------------------------------
    # Classification
    # --------------------------------------------------------

    if (-not $AccountEnabled) {

        $Category = "Disabled"

        $Reason = "Account is disabled."

    }
    elseif ($null -eq $LastSuccessfulSignIn) {

        $Category = "NeverSignedIn"

        $Reason = "No successful sign-in activity was recorded."

    }
    else {

        $DaysSinceLastSuccessfulSignIn = (
            $Today - $LastSuccessfulSignIn.Date
        ).Days

        if ($LastSuccessfulSignIn.Date -lt $InactiveThresholdDate) {

            $Category = "Inactive"

            $Reason = "No successful sign-in within the configured inactivity threshold."

        }
        else {

            $Category = "Active"

            $Reason = "Successful sign-in activity is within the configured threshold."

        }
    }

    # --------------------------------------------------------
    # Governance candidate
    # --------------------------------------------------------

    $GovernanceCandidate = $false

    if (
        $Category -eq "Inactive" -or
        $Category -eq "NeverSignedIn"
    ) {

        $GovernanceCandidate = $true
    }

    # --------------------------------------------------------
    # Result object
    # --------------------------------------------------------

    [PSCustomObject]@{

        Id                            = $User.Id

        DisplayName                  = $User.DisplayName

        UserPrincipalName            = $User.UserPrincipalName

        Mail                          = $User.Mail

        AccountEnabled                = $AccountEnabled

        UserType                     = $User.UserType

        Department                   = $User.Department

        JobTitle                     = $User.JobTitle

        CompanyName                  = $User.CompanyName

        EmployeeId                   = $User.EmployeeId

        EmployeeHireDate             = $User.EmployeeHireDate

        EmployeeLeaveDateTime        = $User.EmployeeLeaveDateTime

        LastSuccessfulSignInDateTime = $LastSuccessfulSignIn

        DaysSinceLastSuccessfulSignIn = $DaysSinceLastSuccessfulSignIn

        InactivityThresholdDays      = $InactiveDays

        InactivityThresholdDate      = $InactiveThresholdDate

        Category                     = $Category

        GovernanceCandidate          = $GovernanceCandidate

        Reason                       = $Reason
    }
}

# ============================================================
# EXPORT REPORT
# ============================================================

Write-Host ""
Write-Host "[4/5] Generating inactive-user report..." -ForegroundColor Yellow

$Timestamp = Get-Date -Format "yyyyMMdd_HHmmss"

$OutputPath = Join-Path `
    $ReportsPath `
    "InactiveUsers_$Timestamp.csv"

$Results |
    Export-Csv `
        -Path $OutputPath `
        -NoTypeInformation `
        -Encoding UTF8

# ============================================================
# SUMMARY
# ============================================================

Write-Host ""
Write-Host "[5/5] Analysis completed." -ForegroundColor Yellow
Write-Host ""

$TotalUsers = @($Results).Count

$ActiveUsers = @(
    $Results |
    Where-Object {
        $_.Category -eq "Active"
    }
).Count

$InactiveUsers = @(
    $Results |
    Where-Object {
        $_.Category -eq "Inactive"
    }
).Count

$NeverSignedInUsers = @(
    $Results |
    Where-Object {
        $_.Category -eq "NeverSignedIn"
    }
).Count

$DisabledUsers = @(
    $Results |
    Where-Object {
        $_.Category -eq "Disabled"
    }
).Count

$GovernanceCandidates = @(
    $Results |
    Where-Object {
        $_.GovernanceCandidate -eq $true
    }
).Count

# ============================================================
# DISPLAY SUMMARY
# ============================================================

Write-Host "=============================================" -ForegroundColor Cyan
Write-Host " Inactive User Analysis Summary" -ForegroundColor Cyan
Write-Host "=============================================" -ForegroundColor Cyan

Write-Host "Total Users                  : $TotalUsers"
Write-Host "Active Users                 : $ActiveUsers"
Write-Host "Inactive Users               : $InactiveUsers"
Write-Host "Never Signed In              : $NeverSignedInUsers"
Write-Host "Disabled Users               : $DisabledUsers"
Write-Host "Governance Candidates        : $GovernanceCandidates"
Write-Host "Inactivity Threshold         : $InactiveDays days"

Write-Host ""
Write-Host "Report:" -ForegroundColor Green
Write-Host $OutputPath -ForegroundColor Green

Write-Host ""
Write-Host "Classification:" -ForegroundColor Cyan
Write-Host "  Active       = Successful sign-in within threshold"
Write-Host "  Inactive     = No successful sign-in within threshold"
Write-Host "  NeverSignedIn = No successful sign-in recorded"
Write-Host "  Disabled     = Account is disabled"

Write-Host ""
Write-Host "Governance candidates are READ-ONLY findings." -ForegroundColor Yellow
Write-Host "No Entra ID accounts were modified." -ForegroundColor Green
Write-Host ""
Write-Host "Script completed successfully." -ForegroundColor Green
Write-Host ""