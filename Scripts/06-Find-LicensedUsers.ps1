#requires -Version 5.1

<#
.SYNOPSIS
    Identifies Microsoft Entra ID licensed users that may require
    license governance review.

.DESCRIPTION
    Reads the latest Entra user discovery report generated by
    01-Get-EntraUsers.ps1 and evaluates licensed accounts.

    The script identifies:

    - Active licensed users
    - Inactive licensed users
    - Never-signed-in licensed users
    - Licensed users with expired leave dates
    - Disabled licensed users
    - Disabled licensed users with expired leave dates

    Governance priority is calculated based on account state,
    sign-in activity, and employee leave date.

    The script is READ-ONLY.

    No licenses are removed and no user accounts are modified.

.PARAMETER InactiveDays
    Number of days without a successful sign-in before an enabled
    licensed user is considered inactive.

    Default:
        90 days

.EXAMPLE
    .\06-Find-LicensedUsers.ps1

    Uses the default 90-day inactivity threshold.

.EXAMPLE
    .\06-Find-LicensedUsers.ps1 -InactiveDays 30

    Uses a 30-day inactivity threshold.

.NOTES
    Project:
        Entra ID User Governance Toolkit

    Script:
        06-Find-LicensedUsers.ps1

    Version:
        1.0.0

    Data source:
        Reports\EntraUsers_*.csv

    Action:
        Read-only
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory = $false)]
    [ValidateRange(1, 3650)]
    [int]$InactiveDays = 90
)

$ErrorActionPreference = "Stop"

# ============================================================
# PROJECT PATH
# ============================================================

$ProjectRoot = Split-Path -Parent $PSScriptRoot

$ReportsPath = Join-Path $ProjectRoot "Reports"

if (-not (Test-Path $ReportsPath)) {

    New-Item `
        -Path $ReportsPath `
        -ItemType Directory `
        -Force |
        Out-Null
}

# ============================================================
# HEADER
# ============================================================

Write-Host ""
Write-Host "=============================================" -ForegroundColor Cyan
Write-Host " Entra ID User Governance Toolkit" -ForegroundColor Cyan
Write-Host " 06 - Find Licensed Users" -ForegroundColor Cyan
Write-Host "=============================================" -ForegroundColor Cyan
Write-Host ""

Write-Host "License inactivity threshold: $InactiveDays days" -ForegroundColor Yellow
Write-Host ""

# ============================================================
# FIND LATEST USER DISCOVERY REPORT
# ============================================================

Write-Host "[1/7] Searching for Entra user discovery report..." -ForegroundColor Yellow

$InputReports = @(
    Get-ChildItem `
        -Path $ReportsPath `
        -Filter "EntraUsers_*.csv" `
        -File `
        -ErrorAction SilentlyContinue |
    Sort-Object LastWriteTime -Descending
)

if ($InputReports.Count -eq 0) {

    throw @"
No Entra user discovery report was found.

Please run:

.\Scripts\01-Get-EntraUsers.ps1

before running this script.
"@
}

$InputReport = $InputReports[0]

Write-Host "Using report:" -ForegroundColor Green
Write-Host "  $($InputReport.FullName)" -ForegroundColor Green
Write-Host ""

# ============================================================
# IMPORT USER REPORT
# ============================================================

Write-Host "[2/7] Loading Entra user data..." -ForegroundColor Yellow

$Users = @(
    Import-Csv -Path $InputReport.FullName
)

if ($Users.Count -eq 0) {

    throw "The selected Entra user report contains no records."
}

Write-Host "Users loaded: $($Users.Count)" -ForegroundColor Green
Write-Host ""

# ============================================================
# FILTER LICENSED USERS
# ============================================================

Write-Host "[3/7] Identifying licensed users..." -ForegroundColor Yellow

$LicensedUsers = @(
    $Users |
    Where-Object {

        $LicenseCount = 0

        if (
            -not [string]::IsNullOrWhiteSpace(
                [string]$_.AssignedLicenseCount
            )
        ) {

            $ParsedLicenseCount = 0

            if (
                [int]::TryParse(
                    [string]$_.AssignedLicenseCount,
                    [ref]$ParsedLicenseCount
                )
            ) {

                $LicenseCount = $ParsedLicenseCount
            }
        }

        $LicenseCount -gt 0
    }
)

Write-Host "Licensed users found: $($LicensedUsers.Count)" -ForegroundColor Green
Write-Host ""

# ============================================================
# HANDLE NO LICENSED USERS
# ============================================================

if ($LicensedUsers.Count -eq 0) {

    Write-Host "No licensed users were found." -ForegroundColor Yellow

    $Timestamp = Get-Date -Format "yyyyMMdd_HHmmss"

    $EmptyReportPath = Join-Path `
        $ReportsPath `
        "LicenseGovernance_$Timestamp.csv"

    @(
        [PSCustomObject]@{
            Id                             = ""
            DisplayName                   = ""
            UserPrincipalName             = ""
            Mail                          = ""
            AccountEnabled                = ""
            UserType                      = ""
            Department                    = ""
            JobTitle                      = ""
            CompanyName                   = ""
            EmployeeId                    = ""
            EmployeeLeaveDateTime         = ""
            DaysSinceLeaveDate            = ""
            LastSuccessfulSignInDateTime  = ""
            DaysSinceLastSuccessfulSignIn = ""
            AssignedLicenseCount          = ""
            Category                      = "NoLicensedUsers"
            GovernancePriority            = "None"
            GovernanceCandidate           = $false
            Reason                        = "No licensed users were found in the source report."
        }
    ) |
    Export-Csv `
        -Path $EmptyReportPath `
        -NoTypeInformation `
        -Encoding UTF8

    Write-Host "Report:" -ForegroundColor Green
    Write-Host $EmptyReportPath -ForegroundColor Green
    Write-Host ""
    Write-Host "Script completed successfully." -ForegroundColor Green

    exit 0
}

# ============================================================
# DATE INFORMATION
# ============================================================

$Today = (Get-Date).Date

$InactiveThresholdDate = $Today.AddDays(-$InactiveDays)

Write-Host "[4/7] Evaluating licensed-account governance..." -ForegroundColor Yellow
Write-Host ""
Write-Host "Today:" -ForegroundColor DarkGray
Write-Host "  $($Today.ToString('yyyy-MM-dd'))" -ForegroundColor DarkGray
Write-Host ""
Write-Host "Inactive threshold:" -ForegroundColor DarkGray
Write-Host "  $($InactiveThresholdDate.ToString('yyyy-MM-dd'))" -ForegroundColor DarkGray
Write-Host ""

# ============================================================
# ANALYZE LICENSED USERS
# ============================================================

$Results = foreach ($User in $LicensedUsers) {

    $Category = "LicensedActive"

    $GovernancePriority = "Low"

    $GovernanceCandidate = $false

    $Reason = ""

    $LastSuccessfulSignIn = $null

    $DaysSinceLastSuccessfulSignIn = $null

    $LeaveDate = $null

    $DaysSinceLeaveDate = $null

    # --------------------------------------------------------
    # ACCOUNT STATUS
    # --------------------------------------------------------

    $AccountEnabled = $false

    if ($User.AccountEnabled -eq "True") {
        $AccountEnabled = $true
    }

    # --------------------------------------------------------
    # LICENSE COUNT
    # --------------------------------------------------------

    $LicenseCount = 0

    if (
        -not [string]::IsNullOrWhiteSpace(
            [string]$User.AssignedLicenseCount
        )
    ) {

        $ParsedLicenseCount = 0

        if (
            [int]::TryParse(
                [string]$User.AssignedLicenseCount,
                [ref]$ParsedLicenseCount
            )
        ) {

            $LicenseCount = $ParsedLicenseCount
        }
    }

    # --------------------------------------------------------
    # SUCCESSFUL SIGN-IN
    # --------------------------------------------------------

    $RawSignInDate = $User.LastSuccessfulSignInDateTime

    if (
        -not [string]::IsNullOrWhiteSpace(
            [string]$RawSignInDate
        )
    ) {

        $ParsedSignInDate = [datetime]::MinValue

        $DateParsed = [datetime]::TryParse(
            [string]$RawSignInDate,
            [ref]$ParsedSignInDate
        )

        if ($DateParsed) {

            $LastSuccessfulSignIn = $ParsedSignInDate

            $DaysSinceLastSuccessfulSignIn = (
                $Today - $LastSuccessfulSignIn.Date
            ).Days
        }
    }

    # --------------------------------------------------------
    # EMPLOYEE LEAVE DATE
    # --------------------------------------------------------

    $RawLeaveDate = $User.EmployeeLeaveDateTime

    if (
        -not [string]::IsNullOrWhiteSpace(
            [string]$RawLeaveDate
        )
    ) {

        $ParsedLeaveDate = [datetime]::MinValue

        $LeaveDateParsed = [datetime]::TryParse(
            [string]$RawLeaveDate,
            [ref]$ParsedLeaveDate
        )

        if ($LeaveDateParsed) {

            $LeaveDate = $ParsedLeaveDate.Date

            if ($LeaveDate -lt $Today) {

                $DaysSinceLeaveDate = (
                    $Today - $LeaveDate
                ).Days
            }
        }
    }

    # ========================================================
    # CLASSIFICATION
    # ========================================================

    # --------------------------------------------------------
    # DISABLED + EXPIRED
    # --------------------------------------------------------

    if (
        -not $AccountEnabled -and
        $LeaveDate -ne $null -and
        $LeaveDate -lt $Today
    ) {

        $Category = "LicensedDisabledExpired"

        $GovernancePriority = "High"

        $GovernanceCandidate = $true

        $Reason = "Disabled licensed account has an expired employee leave date."
    }

    # --------------------------------------------------------
    # DISABLED
    # --------------------------------------------------------

    elseif (-not $AccountEnabled) {

        $Category = "LicensedDisabled"

        $GovernancePriority = "Medium"

        $GovernanceCandidate = $true

        $Reason = "Disabled account still has assigned licenses."
    }

    # --------------------------------------------------------
    # ENABLED + EXPIRED
    # --------------------------------------------------------

    elseif (
        $LeaveDate -ne $null -and
        $LeaveDate -lt $Today
    ) {

        $Category = "LicensedExpired"

        $GovernancePriority = "Critical"

        $GovernanceCandidate = $true

        $Reason = "Enabled licensed account has an expired employee leave date."
    }

    # --------------------------------------------------------
    # ENABLED + NEVER SIGNED IN
    # --------------------------------------------------------

    elseif ($LastSuccessfulSignIn -eq $null) {

        $Category = "LicensedNeverSignedIn"

        $GovernancePriority = "High"

        $GovernanceCandidate = $true

        $Reason = "Enabled licensed account has no recorded successful sign-in activity."
    }

    # --------------------------------------------------------
    # ENABLED + INACTIVE
    # --------------------------------------------------------

    elseif (
        $LastSuccessfulSignIn.Date -lt
        $InactiveThresholdDate
    ) {

        $Category = "LicensedInactive"

        $GovernancePriority = "High"

        $GovernanceCandidate = $true

        $Reason = "Licensed account has no successful sign-in within the configured inactivity threshold."
    }

    # --------------------------------------------------------
    # ACTIVE LICENSED
    # --------------------------------------------------------

    else {

        $Category = "LicensedActive"

        $GovernancePriority = "Low"

        $GovernanceCandidate = $false

        $Reason = "Licensed account has recent successful sign-in activity and no expired leave date."
    }

    # ========================================================
    # RESULT OBJECT
    # ========================================================

    [PSCustomObject]@{

        Id                             = $User.Id

        DisplayName                   = $User.DisplayName

        UserPrincipalName             = $User.UserPrincipalName

        Mail                          = $User.Mail

        AccountEnabled                = $AccountEnabled

        UserType                      = $User.UserType

        Department                    = $User.Department

        JobTitle                      = $User.JobTitle

        CompanyName                   = $User.CompanyName

        EmployeeId                   = $User.EmployeeId

        EmployeeLeaveDateTime         = $LeaveDate

        DaysSinceLeaveDate            = $DaysSinceLeaveDate

        LastSuccessfulSignInDateTime  = $LastSuccessfulSignIn

        DaysSinceLastSuccessfulSignIn = $DaysSinceLastSuccessfulSignIn

        AssignedLicenseCount          = $LicenseCount

        InactivityThresholdDays       = $InactiveDays

        InactivityThresholdDate       = $InactiveThresholdDate

        Category                      = $Category

        GovernancePriority            = $GovernancePriority

        GovernanceCandidate           = $GovernanceCandidate

        Reason                        = $Reason
    }
}

# ============================================================
# EXPORT REPORT
# ============================================================

Write-Host ""
Write-Host "[5/7] Generating license governance report..." -ForegroundColor Yellow

$Timestamp = Get-Date -Format "yyyyMMdd_HHmmss"

$OutputPath = Join-Path `
    $ReportsPath `
    "LicenseGovernance_$Timestamp.csv"

$Results |
    Export-Csv `
        -Path $OutputPath `
        -NoTypeInformation `
        -Encoding UTF8

# ============================================================
# SUMMARY
# ============================================================

Write-Host ""
Write-Host "[6/7] Calculating governance summary..." -ForegroundColor Yellow
Write-Host ""

$TotalLicensed = @($Results).Count

$LicensedActive = @(
    $Results |
    Where-Object {
        $_.Category -eq "LicensedActive"
    }
).Count

$LicensedInactive = @(
    $Results |
    Where-Object {
        $_.Category -eq "LicensedInactive"
    }
).Count

$LicensedNeverSignedIn = @(
    $Results |
    Where-Object {
        $_.Category -eq "LicensedNeverSignedIn"
    }
).Count

$LicensedExpired = @(
    $Results |
    Where-Object {
        $_.Category -eq "LicensedExpired"
    }
).Count

$LicensedDisabled = @(
    $Results |
    Where-Object {
        $_.Category -eq "LicensedDisabled"
    }
).Count

$LicensedDisabledExpired = @(
    $Results |
    Where-Object {
        $_.Category -eq "LicensedDisabledExpired"
    }
).Count

$CriticalCandidates = @(
    $Results |
    Where-Object {
        $_.GovernancePriority -eq "Critical"
    }
).Count

$HighCandidates = @(
    $Results |
    Where-Object {
        $_.GovernancePriority -eq "High"
    }
).Count

$MediumCandidates = @(
    $Results |
    Where-Object {
        $_.GovernancePriority -eq "Medium"
    }
).Count

$GovernanceCandidates = @(
    $Results |
    Where-Object {
        $_.GovernanceCandidate -eq $true
    }
).Count

# ============================================================
# DISPLAY SUMMARY
# ============================================================

Write-Host "[7/7] Analysis completed." -ForegroundColor Yellow
Write-Host ""

Write-Host "=============================================" -ForegroundColor Cyan
Write-Host " License Governance Summary" -ForegroundColor Cyan
Write-Host "=============================================" -ForegroundColor Cyan

Write-Host "Total Licensed Users              : $TotalLicensed"
Write-Host "Licensed + Active                 : $LicensedActive"
Write-Host "Licensed + Inactive               : $LicensedInactive"
Write-Host "Licensed + Never Signed In        : $LicensedNeverSignedIn"
Write-Host "Licensed + Expired Leave Date     : $LicensedExpired"
Write-Host "Licensed + Disabled               : $LicensedDisabled"
Write-Host "Licensed + Disabled + Expired     : $LicensedDisabledExpired"

Write-Host ""
Write-Host "Governance Priority:" -ForegroundColor Cyan
Write-Host "  Critical                        : $CriticalCandidates"
Write-Host "  High                            : $HighCandidates"
Write-Host "  Medium                          : $MediumCandidates"

Write-Host ""
Write-Host "Governance Candidates              : $GovernanceCandidates"

Write-Host ""
Write-Host "Report:" -ForegroundColor Green
Write-Host $OutputPath -ForegroundColor Green

Write-Host ""
Write-Host "Classification:" -ForegroundColor Cyan
Write-Host "  LicensedActive"
Write-Host "      Licensed + recent activity + no expired leave date"
Write-Host ""
Write-Host "  LicensedInactive"
Write-Host "      Licensed + no successful sign-in within threshold"
Write-Host ""
Write-Host "  LicensedNeverSignedIn"
Write-Host "      Licensed + no successful sign-in recorded"
Write-Host ""
Write-Host "  LicensedExpired"
Write-Host "      Licensed + enabled + expired leave date"
Write-Host ""
Write-Host "  LicensedDisabled"
Write-Host "      Licensed + disabled account"
Write-Host ""
Write-Host "  LicensedDisabledExpired"
Write-Host "      Licensed + disabled + expired leave date"

Write-Host ""
Write-Host "Governance candidates are READ-ONLY findings." -ForegroundColor Yellow
Write-Host "No licenses were removed." -ForegroundColor Green
Write-Host "No Entra ID accounts were modified." -ForegroundColor Green
Write-Host ""
Write-Host "Script completed successfully." -ForegroundColor Green
Write-Host ""