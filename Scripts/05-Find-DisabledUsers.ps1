#requires -Version 5.1

<#
.SYNOPSIS
    Identifies disabled Microsoft Entra ID users that may require governance review.

.DESCRIPTION
    Reads the latest Entra user discovery report generated by
    01-Get-EntraUsers.ps1 and evaluates disabled accounts.

    The script identifies:

    - Disabled accounts with licenses
    - Disabled accounts with recent successful sign-in activity
    - Disabled accounts whose employee leave date has passed
    - Disabled accounts that never successfully signed in
    - Disabled accounts without a leave date
    - Standard disabled accounts

    The script is READ-ONLY.

    No user account is modified, enabled, disabled, deleted,
    or unlicensed.

.EXAMPLE
    .\05-Find-DisabledUsers.ps1

.NOTES
    Project:
        Entra ID User Governance Toolkit

    Script:
        05-Find-DisabledUsers.ps1

    Version:
        1.0.0

    Data source:
        Reports\EntraUsers_*.csv

    Action:
        Read-only
#>

[CmdletBinding()]
param()

$ErrorActionPreference = "Stop"

# ============================================================
# PROJECT PATH
# ============================================================

$ProjectRoot = Split-Path -Parent $PSScriptRoot

$ReportsPath = Join-Path $ProjectRoot "Reports"

if (-not (Test-Path $ReportsPath)) {

    New-Item `
        -Path $ReportsPath `
        -ItemType Directory `
        -Force |
        Out-Null
}

# ============================================================
# HEADER
# ============================================================

Write-Host ""
Write-Host "=============================================" -ForegroundColor Cyan
Write-Host " Entra ID User Governance Toolkit" -ForegroundColor Cyan
Write-Host " 05 - Find Disabled Users" -ForegroundColor Cyan
Write-Host "=============================================" -ForegroundColor Cyan
Write-Host ""

# ============================================================
# FIND LATEST USER DISCOVERY REPORT
# ============================================================

Write-Host "[1/6] Searching for Entra user discovery report..." -ForegroundColor Yellow

$InputReports = @(
    Get-ChildItem `
        -Path $ReportsPath `
        -Filter "EntraUsers_*.csv" `
        -File `
        -ErrorAction SilentlyContinue |
    Sort-Object LastWriteTime -Descending
)

if ($InputReports.Count -eq 0) {

    throw @"
No Entra user discovery report was found.

Please run:

.\Scripts\01-Get-EntraUsers.ps1

before running this script.
"@
}

$InputReport = $InputReports[0]

Write-Host "Using report:" -ForegroundColor Green
Write-Host "  $($InputReport.FullName)" -ForegroundColor Green
Write-Host ""

# ============================================================
# IMPORT USER REPORT
# ============================================================

Write-Host "[2/6] Loading Entra user data..." -ForegroundColor Yellow

$Users = @(
    Import-Csv -Path $InputReport.FullName
)

if ($Users.Count -eq 0) {

    throw "The selected Entra user report contains no records."
}

Write-Host "Users loaded: $($Users.Count)" -ForegroundColor Green
Write-Host ""

# ============================================================
# FILTER DISABLED USERS
# ============================================================

Write-Host "[3/6] Identifying disabled users..." -ForegroundColor Yellow

$DisabledUsers = @(
    $Users |
    Where-Object {
        $_.AccountEnabled -eq "False"
    }
)

Write-Host "Disabled users found: $($DisabledUsers.Count)" -ForegroundColor Green
Write-Host ""

# ============================================================
# HANDLE NO DISABLED USERS
# ============================================================

if ($DisabledUsers.Count -eq 0) {

    Write-Host "No disabled users were found." -ForegroundColor Yellow

    $Timestamp = Get-Date -Format "yyyyMMdd_HHmmss"

    $EmptyReportPath = Join-Path `
        $ReportsPath `
        "DisabledUsers_$Timestamp.csv"

    @(
        [PSCustomObject]@{
            Id                             = ""
            DisplayName                   = ""
            UserPrincipalName             = ""
            Mail                          = ""
            AccountEnabled                = ""
            UserType                      = ""
            Department                    = ""
            JobTitle                      = ""
            CompanyName                   = ""
            EmployeeId                    = ""
            EmployeeLeaveDateTime         = ""
            DaysSinceLeaveDate            = ""
            LastSuccessfulSignInDateTime  = ""
            DaysSinceLastSuccessfulSignIn = ""
            AssignedLicenseCount          = ""
            HasLicense                    = ""
            Category                      = "NoDisabledUsers"
            GovernanceCandidate           = $false
            Reason                        = "No disabled users were found in the source report."
        }
    ) |
    Export-Csv `
        -Path $EmptyReportPath `
        -NoTypeInformation `
        -Encoding UTF8

    Write-Host "Report:" -ForegroundColor Green
    Write-Host $EmptyReportPath -ForegroundColor Green
    Write-Host ""
    Write-Host "Script completed successfully." -ForegroundColor Green

    exit 0
}

# ============================================================
# DATE INFORMATION
# ============================================================

$Today = (Get-Date).Date

Write-Host "[4/6] Evaluating disabled-account governance indicators..." -ForegroundColor Yellow
Write-Host ""
Write-Host "Today:" -ForegroundColor DarkGray
Write-Host "  $($Today.ToString('yyyy-MM-dd'))" -ForegroundColor DarkGray
Write-Host ""

# ============================================================
# ANALYZE DISABLED USERS
# ============================================================

$Results = foreach ($User in $DisabledUsers) {

    $Category = "DisabledStandard"

    $Reason = ""

    $LastSuccessfulSignIn = $null

    $DaysSinceLastSuccessfulSignIn = $null

    $LeaveDate = $null

    $DaysSinceLeaveDate = $null

    # --------------------------------------------------------
    # LICENSE COUNT
    # --------------------------------------------------------

    $LicenseCount = 0

    if (
        -not [string]::IsNullOrWhiteSpace(
            [string]$User.AssignedLicenseCount
        )
    ) {

        $ParsedLicenseCount = 0

        if (
            [int]::TryParse(
                [string]$User.AssignedLicenseCount,
                [ref]$ParsedLicenseCount
            )
        ) {

            $LicenseCount = $ParsedLicenseCount
        }
    }

    $HasLicense = $LicenseCount -gt 0

    # --------------------------------------------------------
    # SUCCESSFUL SIGN-IN
    # --------------------------------------------------------

    $RawSignInDate = $User.LastSuccessfulSignInDateTime

    if (
        -not [string]::IsNullOrWhiteSpace(
            [string]$RawSignInDate
        )
    ) {

        $ParsedSignInDate = [datetime]::MinValue

        $DateParsed = [datetime]::TryParse(
            [string]$RawSignInDate,
            [ref]$ParsedSignInDate
        )

        if ($DateParsed) {

            $LastSuccessfulSignIn = $ParsedSignInDate

            $DaysSinceLastSuccessfulSignIn = (
                $Today - $LastSuccessfulSignIn.Date
            ).Days
        }
    }

    # --------------------------------------------------------
    # EMPLOYEE LEAVE DATE
    # --------------------------------------------------------

    $RawLeaveDate = $User.EmployeeLeaveDateTime

    if (
        -not [string]::IsNullOrWhiteSpace(
            [string]$RawLeaveDate
        )
    ) {

        $ParsedLeaveDate = [datetime]::MinValue

        $LeaveDateParsed = [datetime]::TryParse(
            [string]$RawLeaveDate,
            [ref]$ParsedLeaveDate
        )

        if ($LeaveDateParsed) {

            $LeaveDate = $ParsedLeaveDate.Date

            if ($LeaveDate -lt $Today) {

                $DaysSinceLeaveDate = (
                    $Today - $LeaveDate
                ).Days
            }
        }
    }

    # --------------------------------------------------------
    # CLASSIFICATION
    # --------------------------------------------------------

    if (
        $HasLicense -and
        $LeaveDate -ne $null -and
        $LeaveDate -lt $Today
    ) {

        $Category = "DisabledWithLicenseAndExpired"

        $Reason = "Disabled account has assigned licenses and an expired employee leave date."

    }
    elseif (
        $HasLicense
    ) {

        $Category = "DisabledWithLicense"

        $Reason = "Disabled account still has one or more assigned licenses."

    }
    elseif (
        $LastSuccessfulSignIn -ne $null -and
        $LastSuccessfulSignIn.Date -ge $Today.AddDays(-30)
    ) {

        $Category = "DisabledWithRecentActivity"

        $Reason = "Disabled account has successful sign-in activity within the last 30 days."

    }
    elseif (
        $LeaveDate -ne $null -and
        $LeaveDate -lt $Today
    ) {

        $Category = "DisabledExpired"

        $Reason = "Disabled account has an expired employee leave date."

    }
    elseif (
        $LastSuccessfulSignIn -eq $null
    ) {

        $Category = "DisabledNeverSignedIn"

        $Reason = "Disabled account has no recorded successful sign-in activity."

    }
    elseif (
        $LeaveDate -eq $null
    ) {

        $Category = "DisabledNoLeaveDate"

        $Reason = "Disabled account has no employee leave date configured."

    }
    else {

        $Category = "DisabledStandard"

        $Reason = "Disabled account has no additional governance indicator."

    }

    # --------------------------------------------------------
    # GOVERNANCE CANDIDATE
    # --------------------------------------------------------

    $GovernanceCandidate = $false

    if (
        $Category -eq "DisabledWithLicenseAndExpired" -or
        $Category -eq "DisabledWithLicense" -or
        $Category -eq "DisabledWithRecentActivity" -or
        $Category -eq "DisabledExpired"
    ) {

        $GovernanceCandidate = $true
    }

    # --------------------------------------------------------
    # RESULT OBJECT
    # --------------------------------------------------------

    [PSCustomObject]@{

        Id                             = $User.Id

        DisplayName                   = $User.DisplayName

        UserPrincipalName             = $User.UserPrincipalName

        Mail                          = $User.Mail

        AccountEnabled                = $false

        UserType                      = $User.UserType

        Department                    = $User.Department

        JobTitle                      = $User.JobTitle

        CompanyName                   = $User.CompanyName

        EmployeeId                    = $User.EmployeeId

        EmployeeLeaveDateTime         = $LeaveDate

        DaysSinceLeaveDate            = $DaysSinceLeaveDate

        LastSuccessfulSignInDateTime  = $LastSuccessfulSignIn

        DaysSinceLastSuccessfulSignIn = $DaysSinceLastSuccessfulSignIn

        AssignedLicenseCount          = $LicenseCount

        HasLicense                    = $HasLicense

        Category                      = $Category

        GovernanceCandidate            = $GovernanceCandidate

        Reason                        = $Reason
    }
}

# ============================================================
# EXPORT REPORT
# ============================================================

Write-Host ""
Write-Host "[5/6] Generating disabled-user governance report..." -ForegroundColor Yellow

$Timestamp = Get-Date -Format "yyyyMMdd_HHmmss"

$OutputPath = Join-Path `
    $ReportsPath `
    "DisabledUsers_$Timestamp.csv"

$Results |
    Export-Csv `
        -Path $OutputPath `
        -NoTypeInformation `
        -Encoding UTF8

# ============================================================
# SUMMARY
# ============================================================

Write-Host ""
Write-Host "[6/6] Analysis completed." -ForegroundColor Yellow
Write-Host ""

$TotalDisabled = @($Results).Count

$DisabledWithLicense = @(
    $Results |
    Where-Object {
        $_.Category -eq "DisabledWithLicense" -or
        $_.Category -eq "DisabledWithLicenseAndExpired"
    }
).Count

$DisabledWithRecentActivity = @(
    $Results |
    Where-Object {
        $_.Category -eq "DisabledWithRecentActivity"
    }
).Count

$DisabledExpired = @(
    $Results |
    Where-Object {
        $_.Category -eq "DisabledExpired" -or
        $_.Category -eq "DisabledWithLicenseAndExpired"
    }
).Count

$DisabledNeverSignedIn = @(
    $Results |
    Where-Object {
        $_.Category -eq "DisabledNeverSignedIn"
    }
).Count

$DisabledNoLeaveDate = @(
    $Results |
    Where-Object {
        $_.Category -eq "DisabledNoLeaveDate"
    }
).Count

$StandardDisabled = @(
    $Results |
    Where-Object {
        $_.Category -eq "DisabledStandard"
    }
).Count

$GovernanceCandidates = @(
    $Results |
    Where-Object {
        $_.GovernanceCandidate -eq $true
    }
).Count

# ============================================================
# DISPLAY SUMMARY
# ============================================================

Write-Host "=============================================" -ForegroundColor Cyan
Write-Host " Disabled User Governance Summary" -ForegroundColor Cyan
Write-Host "=============================================" -ForegroundColor Cyan

Write-Host "Total Disabled Users             : $TotalDisabled"
Write-Host "Disabled + Licensed              : $DisabledWithLicense"
Write-Host "Disabled + Recent Activity       : $DisabledWithRecentActivity"
Write-Host "Disabled + Expired Leave Date    : $DisabledExpired"
Write-Host "Disabled + Never Signed In       : $DisabledNeverSignedIn"
Write-Host "Disabled + No Leave Date         : $DisabledNoLeaveDate"
Write-Host "Standard Disabled                : $StandardDisabled"
Write-Host "Governance Candidates            : $GovernanceCandidates"

Write-Host ""
Write-Host "Report:" -ForegroundColor Green
Write-Host $OutputPath -ForegroundColor Green

Write-Host ""
Write-Host "Classification:" -ForegroundColor Cyan
Write-Host "  DisabledWithLicenseAndExpired = Disabled + license + expired leave date"
Write-Host "  DisabledWithLicense           = Disabled + assigned license"
Write-Host "  DisabledWithRecentActivity    = Disabled + recent successful sign-in"
Write-Host "  DisabledExpired               = Disabled + expired leave date"
Write-Host "  DisabledNeverSignedIn         = Disabled + no successful sign-in"
Write-Host "  DisabledNoLeaveDate           = Disabled + no leave date"
Write-Host "  DisabledStandard              = No additional governance indicator"

Write-Host ""
Write-Host "Governance candidates are READ-ONLY findings." -ForegroundColor Yellow
Write-Host "No Entra ID accounts were modified." -ForegroundColor Green
Write-Host ""
Write-Host "Script completed successfully." -ForegroundColor Green
Write-Host ""