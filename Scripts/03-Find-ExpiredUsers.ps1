#requires -Version 5.1

<#
.SYNOPSIS
    Identifies expired and upcoming Microsoft Entra ID users
    based on employeeLeaveDateTime.

.DESCRIPTION
    Reads the latest Entra user discovery report generated by
    01-Get-EntraUsers.ps1 and evaluates employeeLeaveDateTime.

    Detection categories:

    - ExpiredEnabled
    - ExpiredDisabled
    - UpcomingLeaver
    - NoLeaveDate
    - InvalidLeaveDate

    The script is READ-ONLY.

    No user account is modified, disabled, deleted, or licensed/unlicensed.

.EXAMPLE
    .\03-Find-ExpiredUsers.ps1

.NOTES
    Project:
        Entra ID User Governance Toolkit

    Script:
        03-Find-ExpiredUsers.ps1

    Version:
        1.0.0

    Data source:
        Reports\EntraUsers_*.csv

    Action:
        Read-only
#>

[CmdletBinding()]
param()

$ErrorActionPreference = "Stop"

# ============================================================
# PROJECT PATH
# ============================================================

$ProjectRoot = Split-Path -Parent $PSScriptRoot

$ReportsPath = Join-Path $ProjectRoot "Reports"

if (-not (Test-Path $ReportsPath)) {

    New-Item `
        -Path $ReportsPath `
        -ItemType Directory `
        -Force |
        Out-Null
}

# ============================================================
# HEADER
# ============================================================

Write-Host ""
Write-Host "=============================================" -ForegroundColor Cyan
Write-Host " Entra ID User Governance Toolkit" -ForegroundColor Cyan
Write-Host " 03 - Find Expired Users" -ForegroundColor Cyan
Write-Host "=============================================" -ForegroundColor Cyan
Write-Host ""

# ============================================================
# FIND LATEST USER DISCOVERY REPORT
# ============================================================

Write-Host "[1/5] Searching for Entra user discovery report..." -ForegroundColor Yellow

$InputReports = @(
    Get-ChildItem `
        -Path $ReportsPath `
        -Filter "EntraUsers_*.csv" `
        -File `
        -ErrorAction SilentlyContinue |
    Sort-Object LastWriteTime -Descending
)

if ($InputReports.Count -eq 0) {

    throw @"
No Entra user discovery report was found.

Please run:

.\Scripts\01-Get-EntraUsers.ps1

before running this script.
"@
}

$InputReport = $InputReports[0]

Write-Host "Using report:" -ForegroundColor Green
Write-Host "  $($InputReport.FullName)" -ForegroundColor Green
Write-Host ""

# ============================================================
# IMPORT USER REPORT
# ============================================================

Write-Host "[2/5] Loading Entra user data..." -ForegroundColor Yellow

$Users = @(
    Import-Csv -Path $InputReport.FullName
)

if ($Users.Count -eq 0) {

    throw "The selected Entra user report contains no records."
}

Write-Host "Users loaded: $($Users.Count)" -ForegroundColor Green
Write-Host ""

# ============================================================
# DATE INFORMATION
# ============================================================

$Today = (Get-Date).Date

Write-Host "[3/5] Evaluating employee leave dates..." -ForegroundColor Yellow
Write-Host ""
Write-Host "Today:" -ForegroundColor DarkGray
Write-Host "  $($Today.ToString('yyyy-MM-dd'))" -ForegroundColor DarkGray
Write-Host ""

# ============================================================
# ANALYZE USERS
# ============================================================

$Results = foreach ($User in $Users) {

    $Category = "NoLeaveDate"

    $Reason = ""

    $LeaveDate = $null

    $DaysSinceLeaveDate = $null

    $DaysUntilLeaveDate = $null

    # --------------------------------------------------------
    # ACCOUNT STATUS
    # --------------------------------------------------------

    $AccountEnabled = $false

    if ($User.AccountEnabled -eq "True") {
        $AccountEnabled = $true
    }

    # --------------------------------------------------------
    # RAW LEAVE DATE
    # --------------------------------------------------------

    $RawLeaveDate = $User.EmployeeLeaveDateTime

    # --------------------------------------------------------
    # NO LEAVE DATE
    # --------------------------------------------------------

    if (
        [string]::IsNullOrWhiteSpace(
            [string]$RawLeaveDate
        )
    ) {

        $Category = "NoLeaveDate"

        $Reason = "No employee leave date is configured."

    }
    else {

        # ----------------------------------------------------
        # PARSE LEAVE DATE
        # ----------------------------------------------------

        $ParsedLeaveDate = [datetime]::MinValue

        $DateParsed = [datetime]::TryParse(
            [string]$RawLeaveDate,
            [ref]$ParsedLeaveDate
        )

        if (-not $DateParsed) {

            $Category = "InvalidLeaveDate"

            $Reason = "Employee leave date could not be parsed."

        }
        else {

            $LeaveDate = $ParsedLeaveDate.Date

            # ------------------------------------------------
            # EXPIRED
            # ------------------------------------------------

            if ($LeaveDate -lt $Today) {

                $DaysSinceLeaveDate = (
                    $Today - $LeaveDate
                ).Days

                if ($AccountEnabled) {

                    $Category = "ExpiredEnabled"

                    $Reason = "Employee leave date has passed and the account is still enabled."

                }
                else {

                    $Category = "ExpiredDisabled"

                    $Reason = "Employee leave date has passed and the account is already disabled."

                }
            }

            # ------------------------------------------------
            # TODAY / UPCOMING
            # ------------------------------------------------

            else {

                $DaysUntilLeaveDate = (
                    $LeaveDate - $Today
                ).Days

                $Category = "UpcomingLeaver"

                if ($DaysUntilLeaveDate -eq 0) {

                    $Reason = "Employee leave date is today."

                }
                else {

                    $Reason = "Employee leave date is in the future."
                }
            }
        }
    }

    # ========================================================
    # GOVERNANCE CANDIDATE
    # ========================================================

    $GovernanceCandidate = $false

    if ($Category -eq "ExpiredEnabled") {

        $GovernanceCandidate = $true
    }

    # ========================================================
    # RESULT OBJECT
    # ========================================================

    [PSCustomObject]@{

        Id                            = $User.Id

        DisplayName                  = $User.DisplayName

        UserPrincipalName            = $User.UserPrincipalName

        Mail                          = $User.Mail

        AccountEnabled                = $AccountEnabled

        UserType                     = $User.UserType

        Department                   = $User.Department

        JobTitle                     = $User.JobTitle

        CompanyName                  = $User.CompanyName

        EmployeeId                   = $User.EmployeeId

        EmployeeHireDate             = $User.EmployeeHireDate

        EmployeeLeaveDateTime        = $LeaveDate

        DaysSinceLeaveDate           = $DaysSinceLeaveDate

        DaysUntilLeaveDate           = $DaysUntilLeaveDate

        Category                     = $Category

        GovernanceCandidate          = $GovernanceCandidate

        Reason                       = $Reason
    }
}

# ============================================================
# EXPORT REPORT
# ============================================================

Write-Host ""
Write-Host "[4/5] Generating expired-user report..." -ForegroundColor Yellow

$Timestamp = Get-Date -Format "yyyyMMdd_HHmmss"

$OutputPath = Join-Path `
    $ReportsPath `
    "ExpiredUsers_$Timestamp.csv"

$Results |
    Export-Csv `
        -Path $OutputPath `
        -NoTypeInformation `
        -Encoding UTF8

# ============================================================
# SUMMARY
# ============================================================

Write-Host ""
Write-Host "[5/5] Analysis completed." -ForegroundColor Yellow
Write-Host ""

$TotalUsers = @($Results).Count

$ExpiredEnabled = @(
    $Results |
    Where-Object {
        $_.Category -eq "ExpiredEnabled"
    }
).Count

$ExpiredDisabled = @(
    $Results |
    Where-Object {
        $_.Category -eq "ExpiredDisabled"
    }
).Count

$UpcomingLeavers = @(
    $Results |
    Where-Object {
        $_.Category -eq "UpcomingLeaver"
    }
).Count

$NoLeaveDate = @(
    $Results |
    Where-Object {
        $_.Category -eq "NoLeaveDate"
    }
).Count

$InvalidLeaveDate = @(
    $Results |
    Where-Object {
        $_.Category -eq "InvalidLeaveDate"
    }
).Count

$GovernanceCandidates = @(
    $Results |
    Where-Object {
        $_.GovernanceCandidate -eq $true
    }
).Count

# ============================================================
# DISPLAY SUMMARY
# ============================================================

Write-Host "=============================================" -ForegroundColor Cyan
Write-Host " Expired User Analysis Summary" -ForegroundColor Cyan
Write-Host "=============================================" -ForegroundColor Cyan

Write-Host "Total Users                  : $TotalUsers"
Write-Host "Expired + Enabled            : $ExpiredEnabled"
Write-Host "Expired + Disabled           : $ExpiredDisabled"
Write-Host "Upcoming Leavers             : $UpcomingLeavers"
Write-Host "No Leave Date                : $NoLeaveDate"
Write-Host "Invalid Leave Date           : $InvalidLeaveDate"
Write-Host "Governance Candidates        : $GovernanceCandidates"

Write-Host ""
Write-Host "Report:" -ForegroundColor Green
Write-Host $OutputPath -ForegroundColor Green

Write-Host ""
Write-Host "Classification:" -ForegroundColor Cyan
Write-Host "  ExpiredEnabled  = Leave date passed + account enabled"
Write-Host "  ExpiredDisabled = Leave date passed + account disabled"
Write-Host "  UpcomingLeaver  = Leave date is today or future"
Write-Host "  NoLeaveDate     = No employee leave date"
Write-Host "  InvalidLeaveDate = Leave date could not be parsed"

Write-Host ""
Write-Host "Governance candidates are READ-ONLY findings." -ForegroundColor Yellow
Write-Host "No Entra ID accounts were modified." -ForegroundColor Green
Write-Host ""
Write-Host "Script completed successfully." -ForegroundColor Green
Write-Host ""