function Inspect-User {

    Clear-Host

    Write-Host ""
    Write-Host "=============================================" -ForegroundColor Cyan
    Write-Host " Inspect User" -ForegroundColor Cyan
    Write-Host "=============================================" -ForegroundColor Cyan
    Write-Host ""

    $SearchText = Read-Host "Enter name or UPN"

    if ([string]::IsNullOrWhiteSpace($SearchText)) {

        return
    }

    $Matches = @(
        $ConsolidatedUsers |
        Where-Object {

            $_.DisplayName -like "*$SearchText*" -or
            $_.UserPrincipalName -like "*$SearchText*"
        }
    )

    if ($Matches.Count -eq 0) {

        Write-Host ""
        Write-Host "No matching users found." -ForegroundColor Yellow
        Write-Host ""

        Read-Host "Press ENTER to return to menu"

        return
    }

    if ($Matches.Count -gt 1) {

        Write-Host ""
        Write-Host "Multiple users found:" -ForegroundColor Yellow
        Write-Host ""

        $Index = 1

        foreach ($Match in $Matches) {

            Write-Host `
                "[$Index] $($Match.DisplayName) - $($Match.UserPrincipalName)"

            $Index++
        }

        Write-Host ""

        $Selection = Read-Host "Select user number"

        $SelectedIndex = 0

        $Parsed = [int]::TryParse(
            $Selection,
            [ref]$SelectedIndex
        )

        if (-not $Parsed) {

            Write-Host `
                "Invalid selection." `
                -ForegroundColor Yellow

            Read-Host "Press ENTER to return to menu"

            return
        }

        if (
            $SelectedIndex -lt 1 -or
            $SelectedIndex -gt $Matches.Count
        ) {

            Write-Host `
                "Invalid selection." `
                -ForegroundColor Yellow

            Read-Host "Press ENTER to return to menu"

            return
        }

        $User = $Matches[$SelectedIndex - 1]
    }
    else {

        $User = $Matches[0]
    }

    Clear-Host

    Write-Host ""
    Write-Host "=============================================" -ForegroundColor Cyan
    Write-Host " User Governance Detail" -ForegroundColor Cyan
    Write-Host "=============================================" -ForegroundColor Cyan
    Write-Host ""

    Write-Host "Identity" -ForegroundColor Yellow
    Write-Host "  Display Name          : $($User.DisplayName)"
    Write-Host "  User Principal Name   : $($User.UserPrincipalName)"
    Write-Host "  User ID               : $($User.UserId)"

    Write-Host ""
    Write-Host "Governance Status" -ForegroundColor Yellow
    Write-Host "  Candidate             : $($User.GovernanceCandidate)"

    $HighestPriority = "None"

    if (
        $User.Priorities -contains "Critical"
    ) {

        $HighestPriority = "Critical"
    }
    elseif (
        $User.Priorities -contains "High"
    ) {

        $HighestPriority = "High"
    }
    elseif (
        $User.Priorities -contains "Review"
    ) {

        $HighestPriority = "Review"
    }

    Write-Host "  Highest Priority      : $HighestPriority"

    Write-Host ""
    Write-Host "Finding Indicators" -ForegroundColor Yellow

    Write-Host "  Inactive              : $($User.Inactive)"
    Write-Host "  Expired               : $($User.Expired)"
    Write-Host "  Guest                 : $($User.Guest)"
    Write-Host "  Disabled              : $($User.Disabled)"
    Write-Host "  Licensed              : $($User.Licensed)"
    Write-Host "  Privileged            : $($User.Privileged)"
    Write-Host "  Excessive Groups      : $($User.ExcessiveGroups)"

    Write-Host ""
    Write-Host "Findings" -ForegroundColor Yellow

    if ($User.Findings.Count -eq 0) {

        Write-Host "  No governance findings."
    }
    else {

        foreach ($Finding in $User.Findings) {

            Write-Host "  - $Finding"
        }
    }

    Write-Host ""
    Write-Host "Reasons" -ForegroundColor Yellow

    if ($User.Reasons.Count -eq 0) {

        Write-Host "  No additional reasons."
    }
    else {

        foreach ($Reason in $User.Reasons) {

            Write-Host "  - $Reason"
        }
    }

    Write-Host ""
    Write-Host "This is a READ-ONLY review." -ForegroundColor Green
    Write-Host "No remediation has been performed." -ForegroundColor Green
    Write-Host ""

    Read-Host "Press ENTER to return to menu"
}

