function Show-AllUsers {

    Clear-Host

    Write-Host ""
    Write-Host "=============================================" -ForegroundColor Cyan
    Write-Host " All Indexed Users" -ForegroundColor Cyan
    Write-Host "=============================================" -ForegroundColor Cyan
    Write-Host ""

    $Rows = @()

    foreach ($User in $ConsolidatedUsers) {

        $Priority = "None"

        if (
            $User.Priorities -contains "Critical"
        ) {

            $Priority = "Critical"
        }
        elseif (
            $User.Priorities -contains "High"
        ) {

            $Priority = "High"
        }
        elseif (
            $User.Priorities -contains "Review"
        ) {

            $Priority = "Review"
        }

        $Rows += [PSCustomObject]@{

            DisplayName       = $User.DisplayName
            UserPrincipalName = $User.UserPrincipalName
            Candidate         = $User.GovernanceCandidate
            Priority          = $Priority
            Findings          = $User.Findings.Count
        }
    }

    $Rows |
        Format-Table `
            DisplayName,
            UserPrincipalName,
            Candidate,
            Priority,
            Findings `
            -AutoSize

    Write-Host ""

    Read-Host "Press ENTER to return to menu"
}

