$UserIndex = @{}

function Ensure-User {

    param(
        [string]$UserId,
        [string]$DisplayName,
        [string]$UserPrincipalName
    )

    if (-not $UserIndex.ContainsKey($UserId)) {

        $UserIndex[$UserId] = [PSCustomObject]@{

            UserId              = $UserId
            DisplayName         = $DisplayName
            UserPrincipalName   = $UserPrincipalName

            Findings            = New-Object System.Collections.Generic.List[string]
            Priorities          = New-Object System.Collections.Generic.List[string]
            Reasons             = New-Object System.Collections.Generic.List[string]

            Inactive            = $false
            Expired             = $false
            Guest               = $false
            Disabled            = $false
            Licensed            = $false
            Privileged          = $false
            ExcessiveGroups     = $false

            GovernanceCandidate = $false
        }
    }

    if (
        [string]::IsNullOrWhiteSpace(
            $UserIndex[$UserId].DisplayName
        )
    ) {

        if (-not [string]::IsNullOrWhiteSpace($DisplayName)) {

            $UserIndex[$UserId].DisplayName = $DisplayName
        }
    }

    if (
        [string]::IsNullOrWhiteSpace(
            $UserIndex[$UserId].UserPrincipalName
        )
    ) {

        if (-not [string]::IsNullOrWhiteSpace($UserPrincipalName)) {

            $UserIndex[$UserId].UserPrincipalName = $UserPrincipalName
        }
    }

    return $UserIndex[$UserId]
}

