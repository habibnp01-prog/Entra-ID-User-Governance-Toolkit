function Search-User {

    Clear-Host

    Write-Host ""
    Write-Host "=============================================" -ForegroundColor Cyan
    Write-Host " Search User" -ForegroundColor Cyan
    Write-Host "=============================================" -ForegroundColor Cyan
    Write-Host ""

    $SearchText = Read-Host "Enter name or UPN"

    if ([string]::IsNullOrWhiteSpace($SearchText)) {

        return
    }

    $Matches = @(
        $ConsolidatedUsers |
        Where-Object {

            $_.DisplayName -like "*$SearchText*" -or
            $_.UserPrincipalName -like "*$SearchText*"
        }
    )

    if ($Matches.Count -eq 0) {

        Write-Host ""
        Write-Host "No matching users found." -ForegroundColor Yellow
        Write-Host ""

        Read-Host "Press ENTER to return to menu"

        return
    }

    Write-Host ""
    Write-Host "Matches:" -ForegroundColor Green
    Write-Host ""

    $Index = 1

    foreach ($User in $Matches) {

        Write-Host "[$Index] $($User.DisplayName)"
        Write-Host "    UPN: $($User.UserPrincipalName)"
        Write-Host "    Governance Candidate: $($User.GovernanceCandidate)"
        Write-Host ""

        $Index++
    }

    Read-Host "Press ENTER to return to menu"
}

